let mês = Number(prompt("Coloque o numero do mês"))
switch (mês) {
    case 1:
        document.write("Janeiro")
        break;
    case 2: 
    document.write("Fevereiro")
    break;
    case 3: 
    document.write("março")
    break;
    default:
        document.write("Você digitou um numero fora do intervalo")
}
