let valor = Number(prompt("Digite a quantidade de pontos"));
switch (valor) {
    case 1:
        document.write("Iniciante");
        break
    case 2:
        document.write("Intermediario");
        break
    case 3:
        document.write("Avançado");
        break
        default:
            document.write("Valor inválido");}
    
   